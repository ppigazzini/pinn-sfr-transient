"""Render the experiment ledger from a directory of study JSONs.

Every published table must be reproducible by a committed command (AGENTS.md), and
that has to include the ledger itself. ``__DEV/EXPERIMENT-LOG.md`` carries the
narrative -- what each experiment asked and what it changed -- and its appendix is
generated by this script from the raw rows, so the numbers in the log cannot drift
from the numbers that were measured.

    uv run python tools/experiment_log.py __DEV/studies

The rows are the ones `axial_study.py` writes. Their shapes are **not** uniform:
the ruler is a dict of meshes, the M9 regime maps have no ``arm`` and no ``T_s``,
and Plan A scores the power trace rather than the temperatures. Rather than force
one schema on them after the fact, this reports whichever of the standard scoring
keys a study actually has, and says so when a key is missing.

Two choices worth stating, both from `AGENTS.md`:

* **The margin is reported as the worst seed, not the mean.** The front is an
  inequality (``max T_c > T_sat + dT_sup``), so an arm that forms one on two seeds
  of three has not formed a front. A mean margin would hide that.
* **``n`` is printed on every row.** Seven claims in this project were overturned
  by the next seed; the sample size belongs next to the number, not in a caveat.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path
from typing import Any

# The scoring keys a temperature study has. A study missing them is not broken --
# the M9 regime maps and Plan A legitimately score other things -- so they are
# reported by presence rather than assumed.
TEMP_KEYS = ("T_s", "L_void_max", "margin_K")


def load(path: Path) -> list[dict]:
    """Rows from one study file, or ``[]`` for the shapes that are not row lists."""
    try:
        data = json.loads(path.read_text(encoding="utf-8") or "null")
    except json.JSONDecodeError:
        return []
    if isinstance(data, dict) or not isinstance(data, list):
        # The ruler writes a mesh-keyed dict. It is a convergence study, not a set
        # of arms, and it is summarised in the log by hand from section 6.5.
        return []
    return [r for r in data if isinstance(r, dict)]


def summarise(rows: list[dict]) -> list[dict[str, Any]]:
    """Per-arm means, worst-seed margin, and the seed count behind each."""
    groups: dict[str, list[dict]] = {}
    for r in rows:
        groups.setdefault(str(r.get("arm", "(no arm)")), []).append(r)
    out = []
    for arm, v in groups.items():
        row: dict[str, Any] = {"arm": arm, "n": len(v)}
        for k in TEMP_KEYS:
            vals = [r[k] for r in v if isinstance(r.get(k), (int, float))]
            vals = [x for x in vals if not math.isnan(x)]
            if not vals:
                continue
            # The margin is the one metric where the mean is the wrong statistic.
            row[k] = min(vals) if k == "margin_K" else sum(vals) / len(vals)
        secs = [r["sec"] for r in v if isinstance(r.get("sec"), (int, float))]
        if secs:
            row["sec"] = sum(secs) / len(secs)
        out.append(row)
    return out


def fmt(row: dict[str, Any]) -> str:
    """One markdown table row; a missing metric prints as an em dash, not as zero."""

    def cell(key: str, spec: str) -> str:
        return f"{row[key]:{spec}}" if key in row else "—"

    front = "—"
    if "margin_K" in row:
        front = "every seed" if row["margin_K"] > 0 else "**lost**"
    return (
        f"| {row['arm']} | {row['n']} | {cell('T_s', '.4f')} | {cell('L_void_max', '.4f')} "
        f"| {cell('margin_K', '+.1f')} | {front} | {cell('sec', '.0f')} |"
    )


def main() -> int:
    """Print the ledger appendix for every study JSON in a directory."""
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("directory", type=Path, help="directory of study JSONs")
    args = ap.parse_args()

    files = sorted(args.directory.glob("*.json"))
    if not files:
        print(f"no study JSONs in {args.directory}", file=sys.stderr)
        return 1

    total_cpu = 0.0
    for f in files:
        rows = load(f)
        if not rows:
            print(f"\n### `{f.name}`\n\nNot a row list — summarised by hand in the log body.")
            continue
        arms = summarise(rows)
        total_cpu += sum(r.get("sec", 0.0) for r in rows)
        scored = any(k in a for a in arms for k in TEMP_KEYS)
        print(f"\n### `{f.name}` — {len(rows)} runs")
        if not scored:
            print(
                f"\n{len(arms)} group(s), scored on keys this table does not carry "
                f"(`{'`, `'.join(sorted(set(rows[0]) - {'arm', 'backend', 'seed'}))[:120]}`)."
            )
            continue
        print("\n| arm | n | `T_s` | `L_void` | worst margin (K) | front | s/run |")
        print("|---|---|---|---|---|---|---|")
        for a in arms:
            print(fmt(a))

    print(f"\n**Total measured CPU across these files: {total_cpu / 3600:.1f} core-hours.**")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
